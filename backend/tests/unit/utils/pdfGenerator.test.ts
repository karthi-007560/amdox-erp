import { inflateSync } from "node:zlib";

import {
    generatePdfBuffer,
} from "../../../src/utils/pdfGenerator";

function extractPdfText(buffer: Buffer): string {
    const pdfSource = buffer.toString("latin1");

    const streams = [
        ...pdfSource.matchAll(/stream\r?\n([\s\S]*?)\r?\nendstream/g),
    ];

    return streams.map((match) => {
        try {
            const content = inflateSync(
                Buffer.from(match[1], "latin1")
            ).toString("latin1");

            const textArrays = [
                ...content.matchAll(/\[([\s\S]*?)\]\s*TJ/g),
            ];

            return textArrays.map((arrayMatch) => {
                const hexStrings = [
                    ...arrayMatch[1].matchAll(/<([0-9a-fA-F]+)>/g),
                ];

                return hexStrings.map((hexMatch) =>
                    Buffer.from(hexMatch[1], "hex").toString("latin1")
                ).join("");
            }).join("\n");
        } catch {
            return "";
        }
    }).join("\n");
}

describe("PDF Generator Utility", () => {
    it("should generate a valid PDF buffer", async () => {
        const buffer = await generatePdfBuffer({
            title: "Employee Report",
            content: "Employee report content.",
        });

        expect(Buffer.isBuffer(buffer)).toBe(true);
        expect(buffer.length).toBeGreaterThan(0);
        expect(buffer.subarray(0, 5).toString()).toBe("%PDF-");
    });

    it("should generate a PDF containing the supplied title", async () => {
        const buffer = await generatePdfBuffer({
            title: "Amdox ERP Report",
            content: "Report content.",
        });

        expect(extractPdfText(buffer)).toContain("Amdox ERP Report");
    });

    it("should generate a PDF containing the supplied content", async () => {
        const buffer = await generatePdfBuffer({
            title: "Test Report",
            content: "This is the employee report content.",
        });

        expect(extractPdfText(buffer))
            .toContain("This is the employee report content.");
    });

    it("should support an optional subtitle", async () => {
        const buffer = await generatePdfBuffer({
            title: "Employee Report",
            subtitle: "November 2026",
            content: "Employee details.",
        });

        expect(extractPdfText(buffer)).toContain("November 2026");
    });

    it("should support an optional footer", async () => {
        const buffer = await generatePdfBuffer({
            title: "Employee Report",
            content: "Employee details.",
            footer: "Generated by Amdox ERP",
        });

        expect(extractPdfText(buffer))
            .toContain("Generated by Amdox ERP");
    });

    it("should generate a PDF with both subtitle and footer", async () => {
        const buffer = await generatePdfBuffer({
            title: "Payroll Report",
            subtitle: "November 2026",
            content: "Payroll information.",
            footer: "Confidential",
        });

        const pdfText = extractPdfText(buffer);

        expect(pdfText).toContain("Payroll Report");
        expect(pdfText).toContain("November 2026");
        expect(pdfText).toContain("Payroll information.");
        expect(pdfText).toContain("Confidential");
    });

    it("should generate a PDF without optional fields", async () => {
        const buffer = await generatePdfBuffer({
            title: "Simple Report",
            content: "Basic report content.",
        });

        expect(buffer.subarray(0, 5).toString()).toBe("%PDF-");
        expect(buffer.length).toBeGreaterThan(0);
    });

    it("should support empty content", async () => {
        const buffer = await generatePdfBuffer({
            title: "Empty Report",
            content: "",
        });

        expect(buffer.subarray(0, 5).toString()).toBe("%PDF-");
        expect(buffer.length).toBeGreaterThan(0);
    });

    it("should support multiline content", async () => {
        const buffer = await generatePdfBuffer({
            title: "Multiline Report",
            content: "First line.\nSecond line.\nThird line.",
        });

        const pdfText = extractPdfText(buffer);

        expect(pdfText).toContain("First line.");
        expect(pdfText).toContain("Second line.");
        expect(pdfText).toContain("Third line.");
    });

    it("should support long report content", async () => {
        const longContent = "Amdox ERP report content. ".repeat(500);

        const buffer = await generatePdfBuffer({
            title: "Long Report",
            content: longContent,
        });

        expect(buffer.subarray(0, 5).toString()).toBe("%PDF-");
        expect(buffer.length).toBeGreaterThan(1000);
    });

    it("should return a Promise", async () => {
        const result = generatePdfBuffer({
            title: "Promise Test",
            content: "Testing promise.",
        });

        expect(result).toBeInstanceOf(Promise);

        const buffer = await result;

        expect(Buffer.isBuffer(buffer)).toBe(true);
    });
});
